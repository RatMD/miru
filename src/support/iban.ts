/**
 * Validate a registered IBAN format and its ISO 7064 MOD 97-10 check digits.
 * @param value IBAN in electronic or space-grouped form; ASCII lowercase is accepted.
 * @returns Whether the country format and checksum are valid; account existence is not checked.
 */
function isValidIban(value: string): boolean {
    if (typeof value !== 'string' || /[^A-Za-z0-9 \u00a0]/.test(value)) {
        return false;
    }

    const iban = value.replace(/[ \u00a0]/g, '').toUpperCase();
    if (!/^[A-Z]{2}[0-9]{2}[A-Z0-9]{1,30}$/.test(iban)) {
        return false;
    }

    const format = BBAN_PATTERNS[iban.slice(0, 2)];
    const checkDigits = Number(iban.slice(2, 4));
    if (!format || !format.test(iban.slice(4)) || checkDigits < 2 || checkDigits > 98) {
        return false;
    }

    const rearranged = iban.slice(4) + iban.slice(0, 4);
    let remainder = 0;
    for (const character of rearranged) {
        const code = character.charCodeAt(0);
        const digit = code >= 65 ? code - 55 : code - 48;
        remainder = (remainder * (code >= 65 ? 100 : 10) + digit) % 97;
    }
    return remainder === 1;
}

