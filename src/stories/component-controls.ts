export function controlDefinition(name: string): Definition {
    return definitions[name] ?? { args: {}, argTypes: {} };
}
export function componentControls(name: string): Pick<Definition, 'args' | 'argTypes'> {
    const { args, argTypes } = controlDefinition(name);
    return { args, argTypes };
}
export function controlNames(name: string): string[] {
    return Object.keys(controlDefinition(name).argTypes);
}
